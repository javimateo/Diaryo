/** The shape of the texts: the same for every language. */
export type Messages = Widen<typeof es>;

type Widen<T> = T extends string
  ? string
  : T extends readonly string[]
    ? string[]
    : T extends (...args: infer A) => string
      ? (...args: A) => string
      : { [K in keyof T]: Widen<T[K]> };
